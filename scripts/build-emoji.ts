// Generates src/client/app/emoji-data.ts from Unicode's emoji-test.txt.
// Usage: bun scripts/build-emoji.ts path/to/emoji-test.txt
const [, , input] = process.argv;
if (!input) throw new Error("usage: bun scripts/build-emoji.ts emoji-test.txt");
const lines = (await Bun.file(input).text()).split("\n");
const groups: { name: string; emoji: [string, string][] }[] = [];
for (const line of lines) {
  const group = line.match(/^# group: (.+)$/);
  if (group) {
    if (group[1] !== "Component") groups.push({ name: group[1]!, emoji: [] });
    continue;
  }
  const m = line.match(/; fully-qualified\s+# (\S+) E[\d.]+ (.+)$/);
  if (!m || !groups.length) continue;
  const name = m[2]!;
  // Skin-tone variants are left out to keep the picker compact.
  if (/skin tone/.test(name)) continue;
  groups[groups.length - 1]!.emoji.push([m[1]!, name]);
}
const body = groups
  .map((g) => `  [${JSON.stringify(g.name)}, ${JSON.stringify(g.emoji.map(([e, n]) => `${e} ${n}`).join("|"))}],`)
  .join("\n");
await Bun.write(
  "src/client/app/emoji-data.ts",
  `// Generated by scripts/build-emoji.ts from Unicode emoji-test.txt (Unicode License v3).\nexport const EMOJI_GROUPS: [group: string, entries: string][] = [\n${body}\n];\n`,
);
